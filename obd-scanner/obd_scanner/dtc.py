_SYSTEM_NAMES = {"P": "パワートレイン", "C": "シャシー", "B": "ボディ", "U": "ネットワーク通信"}


def decode_pair(a, b):
    """2 バイトを DTC 文字列（例: P0301）に変換する。0000 は None。"""
    if a == 0 and b == 0:
        return None
    system = _SYSTEM[a >> 6]
    return f"{system}{(a >> 4) & 0x3:X}{a & 0xF:X}{b >> 4:X}{b & 0xF:X}"


def parse_dtc_response(bodies, is_can):
    """モード 03/07/0A の応答（ECU ごとのデータ）から DTC 一覧を取り出す。

    CAN では先頭 1 バイトが DTC の件数。それ以外の通信方式では件数はなく、
    空きは 00 00 で埋められる。重複は除いて登場順に返す。
    """
    codes = []
    for body in bodies:
        data = body[1:] if is_can and body else body
        for i in range(0, len(data) - 1, 2):
            code = decode_pair(data[i], data[i + 1])
            if code and code not in codes:
                codes.append(code)
    return codes


def describe(code):
    """DTC の日本語説明を返す。"""
    if code in DESCRIPTIONS:
        return DESCRIPTIONS[code]
    system = _SYSTEM_NAMES.get(code[0], "")
    if code[1] in "13" or (code[0] == "U" and code[1] == "2") or (code[0] in "BC" and code[1] == "2"):
        return f"メーカー独自コード（{system}）— 整備書・専用診断機で確認してください"
    if code[0] == "P":
        group = _P_GROUPS.get(code[2])
        if group:
            return f"汎用コード（{group}）"
    return f"汎用コード（{system}）"
